import { checkRecharge } from "../../controllers/retailer/mroboticsController.js";
import * as smepay from "../../controllers/retailer/smepayController.js";
import { getAppConfig } from "../../controllers/retailer/demoController.js";
import express from "express";
import * as auth from "../../controllers/retailer/authController.js";
import * as retailer from "../../controllers/retailer/retailerController.js";
import * as payment from "../../controllers/retailer/paymentController.js";
import retailerRouteProtector from "../../middlewares/retailerRouteProtector.js";
import { rateLimit } from "../../middlewares/authentication.js";
const router = express.Router();
router.get("/config", getAppConfig);
router.post("/login", rateLimit(10), auth.loginRetailer);
router.post("/interests", rateLimit(5, 60000), auth.registerInterest);
router.post("/refresh", rateLimit(20), auth.refreshSession);
router.post("/password-reset/request", rateLimit(5), auth.requestPasswordReset);
router.post("/password-reset/verify", rateLimit(10), auth.verifyOtp);
router.post("/password-reset/complete", rateLimit(10), auth.resetPassword);
router.get("/privacy-policy", retailer.getPrivacyPolicy);
router.get("/developer", retailer.getDeveloper);
router.post("/payments/smepay/webhook", rateLimit(120), smepay.webhook);
router.use(retailerRouteProtector);
router.post("/logout", auth.logoutRetailer);
router.get("/profile", auth.getRetailerProfile);
router.patch("/profile", rateLimit(10), auth.updateRetailerProfile);
router.post("/security/otp/request", rateLimit(5), auth.requestSecurityOtp);
router.post("/security/otp/verify", rateLimit(10), auth.verifyOtp);
router.post("/security/password", rateLimit(10), auth.resetPassword);
router.post("/security/email", rateLimit(10), auth.completeEmailChange);
router.post("/security/phone", rateLimit(10), auth.completePhoneVerification);
router.post("/security/mpin/reset", rateLimit(10), auth.resetMpin);
router.post("/security/mpin", rateLimit(10), auth.changeMpin);
router.get("/operators", retailer.getOperators);
router.get("/circles", retailer.getCircles);
router.get("/plans", retailer.getPlans);
router.get("/commissions", retailer.getCommissions);
router.get("/help", retailer.getHelp);
router.get("/wallet", retailer.getWallet);
router.get("/wallet/entries", retailer.getWalletEntries);
router.get("/wallet/topups/:id/checkout", rateLimit(20), smepay.getCheckout);
router.post("/wallet/topups/:id/status", rateLimit(30), smepay.checkPayment);
router.post("/wallet/topups", rateLimit(20), payment.createWalletTopup);
router.post("/recharges/:id/status", rateLimit(20), checkRecharge);
router.post("/recharges", rateLimit(20), payment.createRecharge);
router.post("/dth/lookup", retailer.lookupDthCustomer);
router.post("/operators/lookup", retailer.lookupMobileOperator);
router.get("/transactions", retailer.getTransactions);
router.get("/transactions/:id", retailer.getTransaction);
router.get("/transactions/:id/gift-code", payment.getGiftCode);
export default router;
